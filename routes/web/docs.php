<?php

declare(strict_types=1);

use App\Docs\OpenApiDocument;
use Illuminate\Support\Facades\Route;

/*
| API documentation (public for the prototype, works offline):
|   /docs               Swagger UI served from public/vendor/swagger-ui (node scripts/copy-swagger-ui.mjs)
|   /docs/openapi.json  OpenAPI 3.1 generated by Scramble + App\Docs\OpenApiDocument
|   /docs/postman.json  Postman v2.1 collection (php artisan api:postman)
| Scramble's own Stoplight Elements UI (needs a CDN) stays available at /docs/api.
*/

Route::get('docs', fn () => response()->view('docs.index'))->name('docs');

Route::get('docs/openapi.json', fn () => response()->json(OpenApiDocument::build(), 200, [], JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_PRETTY_PRINT))
    ->name('docs.openapi');

Route::get('docs/postman.json', function () {
    $path = base_path('docs/postman/epfd-api.postman_collection.json');
    abort_unless(is_file($path), 404, 'Run php artisan api:postman first.');

    return response()->file($path, ['Content-Type' => 'application/json']);
})->name('docs.postman');
